import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const player = fs.readFileSync(path.join(root, 'web/player.html'), 'utf8');
const bridge = fs.readFileSync(path.join(root, 'web/mame-web.js'), 'utf8');
const gamepads = fs.readFileSync(path.join(root, 'web/gamepad-manager.js'), 'utf8');
const romApi = fs.readFileSync(path.join(root, 'api/rom.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'roms-manifest.json'), 'utf8'));
const titles = JSON.parse(fs.readFileSync(path.join(root, 'game-titles.json'), 'utf8'));

assert.match(player, /EJS_pathtodata=['"]\/web\/emulatorjs-data\//);
assert.match(player, /fbneo|arcade/i);
assert.match(player, /EJS_gameID/);
assert.match(player, /EJS_defaultOptions/);
assert.match(bridge, /\/api\/rom\//);
assert.match(bridge, /mga-recent-games-v1/);
assert.match(bridge, /mga-favorite-games-v1/);
assert.match(bridge, /\/api\/gamepads/);
assert.match(bridge, /AbortController/);
assert.match(player, /F9/);
assert.match(player, /mga-emulator-exit/);
assert.match(player, /difficulty-setup/);
assert.match(player, /data-difficulty="easy"/);
assert.match(player, /data-difficulty="hard"/);
assert.match(player, /mga-difficulty-mode-v1/);
assert.match(player, /MGA_difficulty/);
for (const token of ['video-aspect-43','video-stretch','video-integer','video-scanlines','video-vignette','video-amber','video-cool','video-soft','VISUAL_KEY','visualHelp']) assert.match(player, new RegExp(token));
assert.match(gamepads, /stableKey/);
assert.match(gamepads, /visibilitychange/);
assert.match(bridge, /\/api\/roms\/check/);
assert.match(bridge, /\/api\/bios\/status/);
assert.match(bridge, /duplicateOf/);
assert.match(romApi, /Accept-Ranges/);
assert.match(romApi, /req\.method === "HEAD"/);
assert.ok(Array.isArray(manifest.files), 'roms-manifest.json precisa conter files');
assert.ok(manifest.files.length > 0, 'o catálogo não pode estar vazio');
assert.ok(Object.keys(titles).length > 0, 'game-titles.json não pode estar vazio');
assert.ok(fs.existsSync(path.join(root, 'web/emulatorjs-data/loader.js')));
assert.ok(fs.existsSync(path.join(root, 'web/emulatorjs-data/cores/fbneo-wasm.data')));
assert.ok(fs.existsSync(path.join(root, 'web/emulatorjs-data/cores/fbalpha2012_cps2-wasm.data')));
console.log(`PASS web-integrity: ${manifest.files.length} itens no catálogo, ${Object.keys(titles).length} títulos, assets FBNeo presentes`);
